!> Driver for [calculation] kind = "lmto": structure + species -> ASA SCF -> parameter file -> DOS file.
module asr_lmto_driver
  use asr_kinds, only: dp, pi
  use asr_input_lmto, only: lmto_input_t
  use asr_asa
  use asr_atom, only: shell_t
  use asr_lmto_cell, only: cell_t, setup_cell
  use asr_report
  !$ use omp_lib, only: omp_get_max_threads
  implicit none
  private
  public :: run_lmto, atom_shells

  real(dp), parameter :: bohr_per_angstrom = 1.0_dp / 0.529177210903_dp

contains

  subroutine run_lmto(inp, ok)
    type(lmto_input_t), intent(in) :: inp
    logical, intent(out) :: ok
    type(asa_input_t) :: ai
    type(asa_result_t) :: res
    type(cell_t) :: cell
    real(dp), allocatable :: egrid(:), dos(:, :, :, :)
    real(dp) :: vcell, sa, sb
    integer :: ic, ia, l, s, ie, u, np
    character(len=:), allocatable :: pfile, dfile
    character(len=8), allocatable :: syms(:)
    real(dp), allocatable :: zc(:), swsc(:)
    integer, allocatable :: nvc(:), natc(:)
    integer :: ru, nthr, ncl
    integer, allocatable :: csp(:)                   ! species of each ASA class
    character(len=8), allocatable :: csym(:)
    real(dp) :: t0, t_scf, t_dos

    ok = .false.
    t0 = rep_wall()
    ai%alat = inp%alat_angstrom * bohr_per_angstrom
    ai%xc = inp%xc; ai%sigma = inp%sigma; ai%nspin = inp%spin; ai%nk = inp%nk; ai%bz = inp%bz
    ai%smear = inp%smear; ai%beta = inp%mixing; ai%maxit = inp%maxit; ai%tol = inp%tolerance
    ai%relativistic = inp%relativistic; ai%zeta0 = inp%zeta0; ai%trace = inp%trace
    ! classes: one per species, or (lattice = "cell", site_classes) one per site
    if (inp%lattice == 'cell' .and. inp%site_classes) then
      ncl = size(inp%site_sp); csp = inp%site_sp
    else
      ncl = size(inp%species); csp = [(ic, ic=1, ncl)]
    end if
    allocate (ai%cls(ncl), csym(ncl))
    do ic = 1, ncl
      associate (sp => inp%species(csp(ic)))
        ai%cls(ic)%z = sp%z; ai%cls(ic)%nval = sp%nval; ai%cls(ic)%spin_sign = sp%spin_sign
        ai%cls(ic)%nvl = sp%konfig(0:2)
        ai%cls(ic)%core = core_shells_for(sp%konfig)
        ai%cls(ic)%atom_shells = atom_shells(sp)
        csym(ic) = sp%symbol
        if (ncl /= size(inp%species)) write (csym(ic), '(a,i0)') trim(sp%symbol), ic
      end associate
    end do

    ! ---- structure
    cell%nat = 1
    select case (inp%lattice)
    case ('fcc'); cell%avec = reshape([0.0_dp, 0.5_dp, 0.5_dp, 0.5_dp, 0.0_dp, 0.5_dp, 0.5_dp, 0.5_dp, 0.0_dp], [3, 3])
    case ('bcc'); cell%avec = reshape([-0.5_dp, 0.5_dp, 0.5_dp, 0.5_dp, -0.5_dp, 0.5_dp, 0.5_dp, 0.5_dp, -0.5_dp], [3, 3])
    case ('sc', 'b2'); cell%avec = reshape([1.0_dp, 0.0_dp, 0.0_dp, 0.0_dp, 1.0_dp, 0.0_dp, 0.0_dp, 0.0_dp, 1.0_dp], [3, 3])
    end select
    if (inp%lattice == 'b2') cell%nat = 2
    if (inp%lattice == 'cell') then
      cell%avec = inp%cell_vec; cell%nat = size(inp%site_sp)
    end if
    allocate (cell%tau(3, cell%nat), cell%isp(cell%nat))
    cell%tau = 0.0_dp; cell%isp = 1
    if (inp%lattice == 'b2') then; cell%tau(:, 2) = 0.5_dp; cell%isp = [1, 2]; end if
    if (inp%lattice == 'cell') then
      cell%tau = inp%site_pos
      if (inp%site_classes) then; cell%isp = [(ia, ia=1, cell%nat)]; else; cell%isp = inp%site_sp; end if
    end if
    call setup_cell(cell)
    if (inp%lattice == 'b2') then
      vcell = ai%alat**3
      sb = (vcell / (4.0_dp * pi / 3.0_dp * (1.0_dp + inp%ratio**3)))**(1.0_dp / 3.0_dp); sa = inp%ratio * sb
      ai%cls(1)%sws = sa; ai%cls(2)%sws = sb
    else
      do ic = 1, ncl; ai%cls(ic)%sws = cell%w * ai%alat; end do      ! equal space-filling spheres
    end if

    print '(a,a)', 'asr lmto  ', inp%name
    print '(a,a,a,f9.5,a,i0,a,a,a,i0)', '  lattice ', inp%lattice, '  a(Bohr)=', ai%alat, '  atoms/cell=', cell%nat, '  xc=', trim(inp%xc), '  spin=', inp%spin
    t_scf = rep_wall()
    call asa_scf(ai, cell, res, verbose=.false.)
    t_scf = rep_wall() - t_scf
    print '(a,l1,a,i0,a,es9.2,a,f10.6,a)', '  SCF converged=', res%converged, '  iterations=', res%iter, '  dV=', res%dv, '  E_F=', res%ef, ' Ry'
    if (.not. res%converged) print '(a)', '  WARNING: SCF did not converge'
    do ic = 1, ncl
      print '(a,a,a,f8.4,a,f9.5,a,f9.5)', '  class ', csym(ic), '  S(Bohr)=', ai%cls(ic)%sws, '  qnet=', res%cls(ic)%qnet, '  moment=', res%cls(ic)%moment
    end do

    ! ---- parameter file
    pfile = inp%workdir//inp%params_file
    open (newunit=u, file=pfile, status='replace', action='write')
    write (u, '(a)') '# '//inp%name//'  (generated by asr lmto; gamma representation, Ry)'
    write (u, '(a,f12.8)') '# E_F = ', res%ef
    write (u, '(a)') '# class symbol  spin l      enu            c          sqrt(Delta)        p            gamma'
    do ic = 1, ncl
      do s = 1, inp%spin
        do l = 0, 2
          write (u, '(i3,2x,a8,2i4,5f15.8)') ic, csym(ic), s, l, res%cls(ic)%pp(l, s)%enu, res%cls(ic)%pp(l, s)%c, &
            res%cls(ic)%pp(l, s)%sqrdel, res%cls(ic)%pp(l, s)%p, res%cls(ic)%pp(l, s)%gamma
        end do
      end do
    end do
    close (u)
    print '(a,a)', '  wrote ', pfile

    ! ---- DOS
    np = inp%npoints
    allocate (egrid(np), dos(np, 0:2, cell%nat, inp%spin))
    do ie = 1, np; egrid(ie) = inp%emin + (inp%emax - inp%emin) * (ie - 1) / real(np - 1, dp); end do
    t_dos = rep_wall()
    call asa_dos(ai, cell, res, inp%dos_nk, egrid, inp%dos_smear, dos)
    dfile = inp%workdir//inp%dos_file
    open (newunit=u, file=dfile, status='replace', action='write')
    write (u, '(a)') '# '//inp%name//'   states/Ry/atom per spin channel; columns: E(Ry) then per atom, per spin: s p d'
    write (u, '(a,f12.8)') '# E_F = ', res%ef
    do ie = 1, np
      write (u, '(f12.6)', advance='no') egrid(ie)
      do ia = 1, cell%nat
        do s = 1, inp%spin
          write (u, '(3es14.6)', advance='no') dos(ie, :, ia, s)
        end do
      end do
      write (u, *)
    end do
    close (u)
    print '(a,a)', '  wrote ', dfile
    t_dos = rep_wall() - t_dos

    ! ---- report (.out)
    nthr = 1
    !$ nthr = omp_get_max_threads()
    ncl_local: block
      integer :: nc
      nc = ncl
      allocate (syms(nc), zc(nc), swsc(nc), nvc(nc), natc(nc))
      do ic = 1, nc
        syms(ic) = csym(ic); zc(ic) = inp%species(csp(ic))%z; nvc(ic) = inp%species(csp(ic))%nval; swsc(ic) = ai%cls(ic)%sws
        natc(ic) = count(cell%isp == ic)
      end do
    end block ncl_local
    call rep_open(ru, inp%workdir//inp%out_file, 'TB-LMTO-ASA self-consistent calculation: '//inp%name, inp%infile, nthr)
    call rep_echo_input(ru, inp%infile)
    call rep_section(ru, 'method')
    call rep_line(ru, 'Hamiltonian   TB-LMTO-ASA, scalar-relativistic='//merge('yes', 'no ', inp%relativistic)//', s p d basis, no combined correction')
    call rep_line(ru, 'XC functional '//trim(inp%xc)//' (libxc), LDA; spin polarised: '//merge('yes', 'no ', inp%spin == 2))
    write (ru, '(a,f6.3)') '  screening sigma (hard-core)  ', inp%sigma
    write (ru, '(a,a,a,i0,a,f8.4,a,f7.3)') '  BZ integration  ', trim(inp%bz), '  nk=', inp%nk, '  smear=', inp%smear, '  mixing=', inp%mixing
    call rep_structure(ru, inp%lattice, ai%alat, cell%avec, cell%tau, cell%isp, syms, swsc)
    call rep_scf_history(ru, syms, res%iter, res%hist_dv, res%hist_ef, res%hist_moment, res%hist_qnet, inp%tolerance, res%converged)
    call rep_classes(ru, syms, zc, nvc, swsc, natc, res%cls, inp%spin, res%ef, res%moment_cell, '')
    call rep_dos_at_ef(ru, syms, egrid, dos, res%ef, inp%dos_smear, inp%spin, &
                       'DOS columns per atom class (k-space tetrahedron/Gaussian, nk='//itoa(inp%dos_nk)//'); not a self-consistency quantity')
    call rep_section(ru, 'timing')
    write (ru, '(a,f10.2,a)') ' SCF  ', t_scf, ' s'
    write (ru, '(a,f10.2,a)') ' DOS  ', t_dos, ' s'
    write (ru, '(a)') ' files written:'
    write (ru, '(a)') '   '//pfile
    write (ru, '(a)') '   '//dfile
    call rep_close(ru, res%converged, rep_wall() - t0)
    print '(a,a)', '  wrote ', inp%workdir//inp%out_file
    ok = res%converged
  end subroutine run_lmto

  !> Neutral-atom shells for the starting potential: core + valence s, d (occupations given), p gets the rest.
  function itoa(i) result(r)
    integer, intent(in) :: i
    character(len=:), allocatable :: r
    character(len=16) :: b
    write (b, '(i0)') i
    r = trim(b)
  end function itoa

  function atom_shells(sp) result(sh)
    use asr_input_lmto, only: lmto_species_t
    type(lmto_species_t), intent(in) :: sp
    type(shell_t), allocatable :: sh(:)
    type(shell_t), allocatable :: core(:)
    real(dp) :: occp
    integer :: n
    core = core_shells_for(sp%konfig)
    occp = real(sp%nval, dp) - sp%occ_s - sp%occ_d
    allocate (sh(size(core) + 3))
    sh(1:size(core)) = core
    n = size(core)
    ! empty shells are left out: they carry no charge, and an empty 3d of an sp element (Al) is not bound in the free atom
    if (sp%occ_s > 0.0_dp) then; n = n + 1; sh(n) = shell_t(sp%konfig(0), 0, sp%occ_s); end if
    if (sp%occ_d > 0.0_dp) then; n = n + 1; sh(n) = shell_t(sp%konfig(2), 2, sp%occ_d); end if
    if (occp > 0.5_dp) then; n = n + 1; sh(n) = shell_t(sp%konfig(1), 1, occp); end if
    sh = sh(1:n)
  end function atom_shells
end module asr_lmto_driver
