!> Driver for [calculation] kind = "lmto": structure + species -> ASA SCF -> parameter file -> DOS file.
module asr_lmto_driver
  use asr_kinds, only: dp, pi
  use asr_input_lmto, only: lmto_input_t
  use asr_asa
  use asr_atom, only: shell_t
  use asr_lmto_cell, only: cell_t, setup_cell
  use asr_runstats, only: tb_dos, cpu_seconds
  use asr_report
  !$ use omp_lib, only: omp_get_max_threads
  implicit none
  private
  public :: run_lmto, atom_shells, rep_from_asa

  real(dp), parameter :: bohr_per_angstrom = 1.0_dp / 0.529177210903_dp

contains

  subroutine run_lmto(inp, ok)
    type(lmto_input_t), intent(in) :: inp
    logical, intent(out) :: ok
    type(asa_input_t) :: ai
    type(asa_result_t) :: res
    type(cell_t) :: cell
    type(rep_run_t) :: rep
    real(dp), allocatable :: egrid(:), dos(:, :, :, :)
    real(dp) :: vcell, sa, sb
    integer :: ic, ia, l, s, ie, u, np, nthr, ncl
    character(len=:), allocatable :: pfile, dfile
    character(len=10) :: start_d, start_t
    integer, allocatable :: csp(:)                   ! species of each ASA class
    character(len=8), allocatable :: csym(:)
    real(dp) :: t0, t_scf, t_dos, c_dos

    ok = .false.
    call date_and_time(start_d, start_t)
    t0 = rep_wall()
    ai%alat = inp%alat_angstrom * bohr_per_angstrom
    ai%xc = inp%xc; ai%sigma = inp%sigma; ai%nspin = inp%spin; ai%nk = inp%nk; ai%bz = inp%bz
    ai%smear = inp%smear; ai%beta = inp%mixing; ai%maxit = inp%maxit; ai%tol = inp%tolerance
    ai%relativistic = inp%relativistic; ai%zeta0 = inp%zeta0; ai%trace = inp%trace
    ai%second_order = inp%second_order; ai%alpha_scale = inp%alpha_scale; ai%std_alpha = inp%std_alpha
    ! classes: one per species, or (lattice = "cell", site_classes) one per site
    if (inp%lattice == 'cell' .and. inp%site_classes) then
      ncl = size(inp%site_sp); csp = inp%site_sp
    else
      ncl = size(inp%species); csp = [(ic, ic=1, ncl)]
    end if
    allocate (ai%cls(ncl), csym(ncl))
    do ic = 1, ncl
      associate (sp => inp%species(csp(ic)))
        ai%cls(ic)%z = sp%z; ai%cls(ic)%nval = sp%nval; ai%cls(ic)%spin_sign = sp%spin_sign
        ai%cls(ic)%nvl = sp%konfig(0:2)
        ai%cls(ic)%core = core_shells_for(sp%konfig)
        ai%cls(ic)%atom_shells = atom_shells(sp)
        csym(ic) = sp%symbol
        if (ncl /= size(inp%species)) write (csym(ic), '(a,i0)') trim(sp%symbol), ic
      end associate
    end do

    ! ---- structure
    cell%nat = 1
    select case (inp%lattice)
    case ('fcc'); cell%avec = reshape([0.0_dp, 0.5_dp, 0.5_dp, 0.5_dp, 0.0_dp, 0.5_dp, 0.5_dp, 0.5_dp, 0.0_dp], [3, 3])
    case ('bcc'); cell%avec = reshape([-0.5_dp, 0.5_dp, 0.5_dp, 0.5_dp, -0.5_dp, 0.5_dp, 0.5_dp, 0.5_dp, -0.5_dp], [3, 3])
    case ('sc', 'b2'); cell%avec = reshape([1.0_dp, 0.0_dp, 0.0_dp, 0.0_dp, 1.0_dp, 0.0_dp, 0.0_dp, 0.0_dp, 1.0_dp], [3, 3])
    end select
    if (inp%lattice == 'b2') cell%nat = 2
    if (inp%lattice == 'cell') then
      cell%avec = inp%cell_vec; cell%nat = size(inp%site_sp)
    end if
    allocate (cell%tau(3, cell%nat), cell%isp(cell%nat))
    cell%tau = 0.0_dp; cell%isp = 1
    if (inp%lattice == 'b2') then; cell%tau(:, 2) = 0.5_dp; cell%isp = [1, 2]; end if
    if (inp%lattice == 'cell') then
      cell%tau = inp%site_pos
      if (inp%site_classes) then; cell%isp = [(ia, ia=1, cell%nat)]; else; cell%isp = inp%site_sp; end if
    end if
    call setup_cell(cell)
    if (inp%lattice == 'b2') then
      vcell = ai%alat**3
      sb = (vcell / (4.0_dp * pi / 3.0_dp * (1.0_dp + inp%ratio**3)))**(1.0_dp / 3.0_dp); sa = inp%ratio * sb
      ai%cls(1)%sws = sa; ai%cls(2)%sws = sb
    else
      do ic = 1, ncl; ai%cls(ic)%sws = cell%w * ai%alat; end do      ! equal space-filling spheres
    end if

    print '(a,a)', 'asr lmto  ', inp%name
    print '(a,a,a,f9.5,a,i0,a,a,a,i0)', '  lattice ', inp%lattice, '  a(Bohr)=', ai%alat, '  atoms/cell=', cell%nat, '  xc=', trim(inp%xc), '  spin=', inp%spin
    t_scf = rep_wall()
    call asa_scf(ai, cell, res, verbose=.false.)
    t_scf = rep_wall() - t_scf
    print '(a,l1,a,i0,a,es9.2,a,f10.6,a)', '  SCF converged=', res%converged, '  iterations=', res%iter, '  dV=', res%dv, '  E_F=', res%ef, ' Ry'
    print '(a,f18.8,a)', '  total energy =', res%etot, ' Ry per atom'
    if (.not. res%converged) print '(a)', '  WARNING: SCF did not converge'
    do ic = 1, ncl
      print '(a,a,a,f8.4,a,f9.5,a,f9.5)', '  class ', csym(ic), '  S(Bohr)=', ai%cls(ic)%sws, '  qnet=', res%cls(ic)%qnet, '  moment=', res%cls(ic)%moment
    end do

    ! ---- parameter file
    pfile = inp%workdir//inp%params_file
    open (newunit=u, file=pfile, status='replace', action='write')
    write (u, '(a)') '# '//inp%name//'  (generated by asr lmto; gamma representation, Ry)'
    write (u, '(a,f12.8)') '# E_F = ', res%ef
    write (u, '(a)') '# class symbol  spin l      enu            c          sqrt(Delta)        p            gamma'
    do ic = 1, ncl
      do s = 1, inp%spin
        do l = 0, 2
          write (u, '(i3,2x,a8,2i4,5f15.8)') ic, csym(ic), s, l, res%cls(ic)%pp(l, s)%enu, res%cls(ic)%pp(l, s)%c, &
            res%cls(ic)%pp(l, s)%sqrdel, res%cls(ic)%pp(l, s)%p, res%cls(ic)%pp(l, s)%gamma
        end do
      end do
    end do
    close (u)
    print '(a,a)', '  wrote ', pfile

    ! ---- DOS
    np = inp%npoints
    allocate (egrid(np), dos(np, 0:2, cell%nat, inp%spin))
    do ie = 1, np; egrid(ie) = inp%emin + (inp%emax - inp%emin) * (ie - 1) / real(np - 1, dp); end do
    t_dos = rep_wall(); c_dos = cpu_seconds()
    call asa_dos(ai, cell, res, inp%dos_nk, egrid, inp%dos_smear, dos)
    res%timer%wall(tb_dos) = rep_wall() - t_dos
    res%timer%cpu(tb_dos) = cpu_seconds() - c_dos
    res%timer%ncall(tb_dos) = 1

    nthr = 1
    !$ nthr = omp_get_max_threads()
    call rep_from_asa(inp, ai, cell, res, egrid, dos, csp, csym, rep, t0, nthr, start_d, start_t)

    dfile = inp%workdir//inp%dos_file
    open (newunit=u, file=dfile, status='replace', action='write')
    call rep_write_dos_header(u, rep, np, inp%emin, inp%emax)
    do ie = 1, np
      write (u, '(f12.6)', advance='no') egrid(ie)
      do ia = 1, cell%nat
        do s = 1, inp%spin
          write (u, '(3es14.6)', advance='no') dos(ie, :, ia, s)
        end do
      end do
      write (u, *)
    end do
    close (u)
    print '(a,a)', '  wrote ', dfile

    call rep_write_report(rep, inp%workdir//inp%out_file)
    print '(a,a)', '  wrote ', inp%workdir//inp%out_file

    call rep_write_json(rep, inp%workdir//rep%json_file)
    print '(a,a)', '  wrote ', inp%workdir//rep%json_file

    ok = res%converged
  end subroutine run_lmto

  !> Fill rep_run_t from k-space asa_result_t
  subroutine rep_from_asa(inp, ai, cell, res, egrid, dos, csp, csym, rep, t0, nthr, start_d, start_t)
    use iso_fortran_env, only: compiler_version, compiler_options
    use asr_build_info, only: git_rev, git_dirty
    use asr_kinds, only: dp, pi
    type(lmto_input_t), intent(in) :: inp
    type(asa_input_t), intent(in) :: ai
    type(cell_t), intent(in) :: cell
    type(asa_result_t), intent(in) :: res
    real(dp), intent(in) :: egrid(:)
    real(dp), intent(in) :: dos(:, 0:, :, :)
    integer, intent(in) :: csp(:)
    character(len=8), intent(in) :: csym(:)
    type(rep_run_t), intent(out) :: rep
    real(dp), intent(in) :: t0
    integer, intent(in) :: nthr
    character(len=10), intent(in) :: start_d, start_t
    integer :: ncl, ic, ia, s, l, ie, np, natc, dot
    real(dp) :: def, val, fsp_k

    ncl = size(csym)
    rep%prog_name = 'asr'
    rep%prog_version = '0.1.0'
    rep%git_rev = git_rev
    rep%git_dirty = git_dirty
    rep%compiler_ver = compiler_version()
    rep%compiler_opts = compiler_options()
    rep%host = get_host()
    rep%pid = get_pid()
    rep%start_date = start_d
    rep%start_time = start_t
    call date_and_time(rep%finish_date, rep%finish_time)
    rep%wall_total = rep_wall() - t0
    rep%mpi_ranks = 1
    rep%omp_threads = nthr
    rep%infile = inp%infile
    rep%fingerprint = fnv1a64_file(inp%infile)
    rep%workdir = inp%workdir
    rep%out_file = inp%out_file
    dot = index(inp%out_file, '.', back=.true.)
    if (dot > 0) then
      rep%json_file = inp%out_file(1:dot - 1)//'.json'
    else
      rep%json_file = trim(inp%out_file)//'.json'
    end if
    rep%dos_file = inp%dos_file
    rep%params_file = inp%params_file
    rep%title = inp%name
    if (allocated(inp%resolved)) rep%resolved = inp%resolved

    ! Method
    rep%method = 'kspace'
    rep%route = 'kspace'
    rep%xc = trim(inp%xc)
    rep%relativistic = inp%relativistic
    rep%nspin = inp%spin
    rep%ncomp = ncl
    rep%k_nk = inp%nk
    rep%k_bz = trim(inp%bz)
    rep%k_smear = inp%smear
    rep%k_dos_nk = inp%dos_nk
    rep%k_sigma = inp%sigma
    rep%mix_type = 'Anderson'
    rep%mix_beta = inp%mixing
    rep%tol = inp%tolerance

    ! Structure
    rep%lattice = trim(inp%lattice)
    rep%alat = ai%alat
    rep%avec = cell%avec
    rep%cell_vol = abs(cell%avec(1, 1) * (cell%avec(2, 2) * cell%avec(3, 3) - cell%avec(3, 2) * cell%avec(2, 3)) &
                     - cell%avec(1, 2) * (cell%avec(2, 1) * cell%avec(3, 3) - cell%avec(3, 1) * cell%avec(2, 3)) &
                     + cell%avec(1, 3) * (cell%avec(2, 1) * cell%avec(3, 2) - cell%avec(3, 1) * cell%avec(2, 2))) * ai%alat**3
    rep%period = 1
    rep%nsite = cell%nat
    rep%nat = cell%nat
    allocate (rep%sites(cell%nat))
    do ia = 1, cell%nat
      rep%sites(ia)%ia = ia
      rep%sites(ia)%species = csym(cell%isp(ia))
      rep%sites(ia)%iclass = cell%isp(ia)
      rep%sites(ia)%pos = cell%tau(:, ia)
      rep%sites(ia)%sws = ai%cls(cell%isp(ia))%sws
    end do
    rep%sws_avg = sum(ai%cls(cell%isp(1:cell%nat))%sws) / real(cell%nat, dp)

    ! Components
    allocate (rep%comp(ncl))
    np = size(egrid)
    if (res%ef <= egrid(1)) then
      ie = 1; def = 0.0_dp
    else if (res%ef >= egrid(np)) then
      ie = np - 1; def = 1.0_dp
    else
      do ie = 1, np - 1
        if (egrid(ie) <= res%ef .and. res%ef <= egrid(ie + 1)) exit
      end do
      def = (res%ef - egrid(ie)) / (egrid(ie + 1) - egrid(ie))
    end if
    fsp_k = merge(2.0_dp, 1.0_dp, inp%spin == 1)

    do ic = 1, ncl
      rep%comp(ic)%label = csym(ic)
      rep%comp(ic)%species = inp%species(csp(ic))%symbol
      rep%comp(ic)%subname = ''
      rep%comp(ic)%z = ai%cls(ic)%z
      rep%comp(ic)%valence = ai%cls(ic)%nval
      natc = count(cell%isp == ic)
      rep%comp(ic)%concentration = 1.0_dp
      rep%comp(ic)%weight_per_site = real(natc, dp) / real(cell%nat, dp)
      rep%comp(ic)%sws = ai%cls(ic)%sws
      rep%comp(ic)%qnet = res%cls(ic)%qnet
      rep%comp(ic)%moment = res%cls(ic)%moment
      rep%comp(ic)%enu = res%cls(ic)%enu
      rep%comp(ic)%q = res%cls(ic)%q
      ! sphere charge of the channel: q0 + p q2 in the generalised problem; q0 with second_order (asa_scf, band energy)
      rep%comp(ic)%qch = res%cls(ic)%q(0, :, :)
      if (.not. ai%second_order) then
        do s = 1, inp%spin
          rep%comp(ic)%qch(:, s) = res%cls(ic)%q(0, :, s) + res%cls(ic)%pp(:, s)%p * res%cls(ic)%q(2, :, s)
        end do
      end if
      do s = 1, inp%spin
        do l = 0, 2
          rep%comp(ic)%c(l, s) = res%cls(ic)%pp(l, s)%c
          rep%comp(ic)%sqrdel(l, s) = res%cls(ic)%pp(l, s)%sqrdel
          rep%comp(ic)%p(l, s) = res%cls(ic)%pp(l, s)%p
          rep%comp(ic)%gamma(l, s) = res%cls(ic)%pp(l, s)%gamma
        end do
      end do
      rep%comp(ic)%dosef = 0.0_dp
      do ia = 1, cell%nat
        if (cell%isp(ia) /= ic) cycle
        do s = 1, inp%spin
          do l = 0, 2
            val = dos(ie, l, ia, s) + def * (dos(ie + 1, l, ia, s) - dos(ie, l, ia, s))
            rep%comp(ic)%dosef(l, s) = rep%comp(ic)%dosef(l, s) + fsp_k * val / real(natc, dp)
          end do
        end do
      end do
      if (allocated(res%ecomp)) rep%comp(ic)%ecomp = res%ecomp(:, ic)
    end do

    ! SCF history and observables
    rep%iter = res%iter
    rep%converged = res%converged
    rep%ef = res%ef
    rep%etot = res%etot
    rep%eterm = res%eterm
    if (allocated(res%ecomp)) rep%ecomp = res%ecomp
    if (allocated(res%hist_etot)) rep%hist_etot = res%hist_etot
    if (allocated(res%hist_dv)) rep%hist_dv = res%hist_dv
    if (allocated(res%hist_ef)) rep%hist_ef = res%hist_ef
    if (allocated(res%hist_wall)) rep%hist_wall = res%hist_wall
    if (allocated(res%hist_moment)) rep%hist_moment = res%hist_moment
    if (allocated(res%hist_qnet)) rep%hist_qnet = res%hist_qnet
    rep%qcell = sum([(count(cell%isp == ic) * res%cls(ic)%qnet, ic=1, ncl)]) / real(cell%nat, dp)
    rep%moment_site = res%moment_cell / real(cell%nat, dp)
    rep%dosef_site = sum([(rep%comp(ic)%weight_per_site * sum(rep%comp(ic)%dosef), ic=1, ncl)])
    rep%eband = res%eband
    rep%sumev = res%sumev

    ! Diagnostics
    rep%nclamp = res%nclamp
    rep%nclamp_run = res%nclamp_run
    rep%below_ok = .true.

    ! Timing: the parts from the SCF and the DOS; the total is the whole run so far, as the end-of-run line
    rep%timer = res%timer
    rep%timer%wall_total = rep%wall_total
    rep%timer%cpu_total = cpu_seconds()
  end subroutine rep_from_asa

  !> Neutral-atom shells for the starting potential: core + valence s, d (occupations given), p gets the rest.
  function itoa(i) result(r)
    integer, intent(in) :: i
    character(len=:), allocatable :: r
    character(len=16) :: b
    write (b, '(i0)') i
    r = trim(b)
  end function itoa

  function atom_shells(sp) result(sh)
    use asr_input_lmto, only: lmto_species_t
    type(lmto_species_t), intent(in) :: sp
    type(shell_t), allocatable :: sh(:)
    type(shell_t), allocatable :: core(:)
    real(dp) :: occp
    integer :: n
    core = core_shells_for(sp%konfig)
    occp = real(sp%nval, dp) - sp%occ_s - sp%occ_d
    allocate (sh(size(core) + 3))
    sh(1:size(core)) = core
    n = size(core)
    ! empty shells are left out: they carry no charge, and an empty 3d of an sp element (Al) is not bound in the free atom
    if (sp%occ_s > 0.0_dp) then; n = n + 1; sh(n) = shell_t(sp%konfig(0), 0, sp%occ_s); end if
    if (sp%occ_d > 0.0_dp) then; n = n + 1; sh(n) = shell_t(sp%konfig(2), 2, sp%occ_d); end if
    if (occp > 0.5_dp) then; n = n + 1; sh(n) = shell_t(sp%konfig(1), 1, occp); end if
    sh = sh(1:n)
  end function atom_shells
end module asr_lmto_driver
